/**
 * Browser build: `src/client.js` -> `lib/client.js`.
 *
 * The web shell hands each plugin a `window.__ModuleLoader__` with a tiny
 * CommonJS-like `require`. The bundle is wrapped so the plugin exports land on
 * `module.exports`, which is what the loader reads back. React and the shell
 * packages stay external and are resolved through `require` at runtime.
 */
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(new URL('.', import.meta.url)));
const entry = join(root, 'src', 'client.js');
const target = join(root, 'lib', 'client.js');

const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const banner = `/**
 * ${packageJson.name} v${packageJson.version} — browser half (generated by scripts/build-client.mjs).
 * Registers the "${packageJson.name}" settings page.
 * Do not edit by hand; edit src/client.js and rebuild.
 */`;

const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['es2022'],
    jsx: 'transform',
    legalComments: 'none',
    logLevel: 'warning',
    // Provided by the web shell at runtime; never bundled.
    external: ['react', 'react-dom', 'react/jsx-runtime'],
});

const code = result.outputFiles[0].text;
const indented = code.split('\n').map(line => (line === '' ? '' : `    ${line}`)).join('\n');

const bundle = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageJson.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${indented}
    var value = module.exports && module.exports.default !== undefined ? module.exports.default : module.exports;
    return value;
  },
});
`;

await mkdir(dirname(target), { recursive: true });
await writeFile(target, bundle, 'utf8');

const kib = (Buffer.byteLength(bundle) / 1024).toFixed(1);
console.log(`build:client  src/client.js -> lib/client.js  (${kib} KiB)`);
